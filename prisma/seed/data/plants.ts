/* ===========================================================================
 * DADOS INICIAIS DA BASE BOTÂNICA
 *
 * Estas espécies existem para demonstrar a estrutura do catálogo e permitir que
 * a busca, os filtros e o recomendador funcionem desde o primeiro `npm run dev`.
 *
 * Todos os registros entram no banco com dataQuality = SEED_UNREVIEWED e são
 * exibidos com o aviso "conteúdo ainda não revisado" até que um administrador
 * confira e promova para REVIEWED.
 *
 * As informações de toxicidade seguem a base de plantas tóxicas e não tóxicas
 * da ASPCA. Onde não houve confirmação em fonte, o campo fica UNKNOWN e a
 * interface exibe "Informação não confirmada" — o sistema nunca preenche uma
 * lacuna botânica com suposição.
 * =========================================================================== */

